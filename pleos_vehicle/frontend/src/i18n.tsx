const dictionaries: Record<Lang, Record<Key, string>> = { en, nl };

export type T = (key: Key | string) => string;

const I18nContext = createContext<{ lang: Lang; t: T }>({ lang: "en", t: (k) => k });

export function I18nProvider({ lang, children }: { lang: Lang; children: ReactNode }) {
  const dict = dictionaries[lang];
  const t: T = (key) => (dict as Record<string, string>)[key] ?? (en as Record<string, string>)[key] ?? key;
  return <I18nContext.Provider value={{ lang, t }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
